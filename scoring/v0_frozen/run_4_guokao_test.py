def run_single_question_suite(cfg, api_key):
    cache_file = OUT_DIR / f"_cache_{cfg['代号']}.json"
    if cache_file.exists():
        cached = json.loads(cache_file.read_text(encoding="utf-8"))
        print(f"  [读取已完成缓存] {cfg['简称']} (耗时 {cached['耗时秒']}s)", flush=True)
        return cached

    t0 = time.time()
    print(f"\n================ 开始处理 {cfg['简称']} ================", flush=True)
    rubric, bundle = prefab_universal_question(
        cfg["路径"], api_key=api_key, ref_limit=cfg["建表参考数"], mode_label=f"零预设通用预制({cfg['建表参考数']}份统计)"
    )
    gates_desc = [f"{g['名称']}({g['分值']}分)" for g in rubric["外壳客观门禁列表"]]
    print(
        f"  [预制完成] 任务块配额={rubric['分池配置']['各任务块封顶配额']} | 自动生长外壳门禁={gates_desc}",
        flush=True,
    )

    blind_ref = bundle["参考答案"][cfg["盲测机构下标"]]
    eval_map = {
        f"盲测高分参考_{blind_ref['来源']}": blind_ref["正文"],
        cfg["瑕疵考生名"]: cfg["瑕疵考生作答"],
    }
    if cfg["额外对照名"]:
        eval_map[cfg["额外对照名"]] = cfg["额外对照作答"]

    graded = {}
    for label, text in eval_map.items():
        res = grade_universal_answer(rubric, text, api_key=api_key, dual_pass=True)
        graded[label] = {"作答原文": text, **res}
        aud = res["双盲审计"]
        print(
            f"  [批改完成] {label}: {res['最终得分']}/{res['满分']} "
            f"(正序={aud['正序独立分']}, 逆序={aud['逆序独立分']}, 双盲差={aud['双盲分差']})",
            flush=True,
        )

    # 对瑕疵考生卷执行“基于原卷微创升格 + 闭环重测验分”
    flawed_res = graded[cfg["瑕疵考生名"]]
    upgraded = upgrade_user_answer_closed_loop(
        rubric, cfg["瑕疵考生作答"], flawed_res, api_key=api_key
    )
    print(
        f"  [微创升格闭环] {cfg['瑕疵考生名']}: {upgraded['原卷得分']}分({upgraded['原卷格数']}格) "
        f"-> {upgraded['升格后得分']}分({upgraded['升格后格数']}格, 提分+{upgraded['实测提分']})",
        flush=True,
    )

    out_obj = {
        "代号": cfg["代号"],
        "简称": cfg["简称"],
        "耗时秒": round(time.time() - t0, 1),
        "预制评分表": rubric,
        "答卷批改结果": graded,
        "原卷微创升格闭环": upgraded,
    }
    cache_file.write_text(json.dumps(out_obj, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return out_obj


