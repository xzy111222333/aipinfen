def main():
    api_key = os.environ["DEEPSEEK_API_KEY"]
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    t0 = time.time()

    # 并行跑两批以兼顾速度与API并发稳定
    results = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:
        futs = [pool.submit(run_single_question_suite, cfg, api_key) for cfg in TEST_SUITE]
        for f in futs:
            results.append(f.result())

    total_sec = time.time() - t0
    json_path = OUT_DIR / "四道反套路国考真题_通用引擎实测.json"
    md_path = OUT_DIR / "四道反套路国考真题_点评与升格实测报告.md"
    json_path.write_text(json.dumps(results, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    md_path.write_text(render_4_questions_markdown(results, total_sec), encoding="utf-8")
    print(f"\n全部4道反套路真题实测完毕！总用时 {total_sec:.1f}s，报告：{md_path}", flush=True)


if __name__ == "__main__":
    main()
